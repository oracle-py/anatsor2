  add column if not exists owner_user_id uuid references auth.users(id) on delete cascade,
  add column if not exists chicks_hatched integer not null default 0,
  add column if not exists birds_bred integer not null default 0,
  add column if not exists eggs_collected integer not null default 0,
  add column if not exists mortality_count integer not null default 0,
  add column if not exists note text,
  add column if not exists created_at timestamptz not null default now(),
  add column if not exists updated_at timestamptz not null default now();

create table if not exists public.alerts (
  id bigint generated by default as identity primary key,
  device_id text not null references public.devices(id) on delete cascade,
  type text not null check (type in ('temp_high','temp_low','humidity_high','humidity_low','air_bad','device_offline')),
  severity text not null check (severity in ('warning','critical')),
  started_at timestamptz not null default now(),
  resolved_at timestamptz,
  read_at timestamptz,
  message text not null
);

