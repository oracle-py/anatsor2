create table if not exists public.daily_records (
  id uuid primary key default gen_random_uuid(),
  device_id text not null references public.devices(id) on delete cascade,
  owner_user_id uuid not null references auth.users(id) on delete cascade,
  record_date date not null,
  chicks_hatched integer not null default 0 check (chicks_hatched >= 0),
  birds_bred integer not null default 0 check (birds_bred >= 0),
  eggs_collected integer not null default 0 check (eggs_collected >= 0),
  mortality_count integer not null default 0 check (mortality_count >= 0),
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (device_id, record_date)
);

-- Bring daily_records created by an older schema up to the current contract.
