-- Safe to run more than once in the Supabase SQL editor.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null,
  full_name text,
  created_at timestamptz not null default now()
);

create table if not exists public.devices (
  id text primary key,
  owner_user_id uuid references auth.users(id) on delete set null,
  name text not null,
  local_hostname text,
  claimed_at timestamptz,
  status text not null default 'offline',
  last_seen_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.sensor_readings (
  id bigint generated by default as identity primary key,
  device_id text not null references public.devices(id) on delete cascade,
  temperature double precision,
  humidity double precision,
  air_quality double precision,
  fan_on boolean not null default false,
  humidifier_on boolean not null default false,
  alarm_active boolean not null default false,
  temperature_high boolean not null default false,
  temperature_low boolean not null default false,
  humidity_high boolean not null default false,
  humidity_low boolean not null default false,
  air_quality_bad boolean not null default false,
  camera_live boolean,
  detection_label text,
  detection_confidence double precision,
  detection_at timestamptz,
  created_at timestamptz not null default now()
);

