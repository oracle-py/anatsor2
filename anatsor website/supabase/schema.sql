create or replace function public.claim_device(requested_device_id text, requested_name text default null)
returns public.devices
language plpgsql
security definer
set search_path = public
as $$
declare
  claimed public.devices;
  normalized_id text := upper(trim(requested_device_id));
begin
  if auth.uid() is null then raise exception 'Authentication required' using errcode = '42501'; end if;
  if normalized_id !~ '^AIPMS[A-Z0-9-]{3,}$' then raise exception 'Invalid device ID'; end if;
  if not exists (select 1 from public.devices where id = normalized_id) then raise exception 'Device not found'; end if;

  update public.devices
  set owner_user_id = auth.uid(),
      name = coalesce(nullif(trim(requested_name), ''), name),
      claimed_at = now()
  where id = normalized_id and owner_user_id is null
  returning * into claimed;

  if claimed.id is null then
    if exists (select 1 from public.devices where id = normalized_id and owner_user_id = auth.uid()) then
      select * into claimed from public.devices where id = normalized_id;
      return claimed;
    end if;
    raise exception 'Device is already registered to another account' using errcode = '23505';
  end if;
  return claimed;
end;
$$;

revoke all on function public.claim_device(text, text) from public;
grant execute on function public.claim_device(text, text) to authenticated;

-- Exposes only an availability boolean so the signup form can give useful
-- feedback without allowing anonymous users to list registered devices.
create or replace function public.is_device_available(candidate_id text)
returns boolean
language sql
security definer
set search_path = public
as $$
  select nullif(trim(candidate_id), '') is not null
    and exists (
      select 1 from public.devices
      where id = upper(trim(candidate_id)) and owner_user_id is null
    );
$$;

revoke all on function public.is_device_available(text) from public;
grant execute on function public.is_device_available(text) to anon, authenticated;

create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, username, full_name) values (new.id, coalesce(nullif(new.raw_user_meta_data->>'username', ''), split_part(new.email, '@', 1)), nullif(new.raw_user_meta_data->>'full_name', ''));
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'sensor_readings'
  ) then
    alter publication supabase_realtime add table public.sensor_readings;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'alerts') then
    alter publication supabase_realtime add table public.alerts;
  end if;
end;
$$;
